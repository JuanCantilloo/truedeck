-- TrueDeck telemetry schema. Run from the Supabase SQL Editor or Supabase CLI.
-- The API uses a server-side DATABASE_URL; do not expose database credentials
-- in frontend code or enable anonymous table access.

create table if not exists public.telemetria (
  id bigint generated by default as identity primary key,
  "idRuta" varchar(50),
  "idVehiculo" varchar(50) not null,
  "fechaHoraLecturaDato" timestamp without time zone,
  "fechaHoraEnvioDato" timestamp without time zone,
  latitud double precision,
  longitud double precision,
  "tipoBus" varchar(20),
  "RangoLatencia" varchar(50),
  "tramaRetransmitida" boolean default false,
  "velocidadVehiculo" double precision default 0.0,
  "aceleracionVehiculo" double precision default 0.0,
  "latenciaMinutos" double precision default 0.0,
  "archivoOrigen" varchar(255),
  "fechaCarga" timestamp without time zone default now()
);

create table if not exists public.archivos_cargados (
  id bigint generated by default as identity primary key,
  nombre varchar(255) not null,
  "totalRegistros" integer default 0,
  "totalConFalla" integer default 0,
  "fechaCarga" timestamp without time zone default now()
);

-- Chunks live in PostgreSQL so separate serverless invocations can assemble
-- an upload without relying on a function's temporary filesystem.
create table if not exists public.upload_chunks (
  upload_id varchar(36) not null,
  chunk_index integer not null,
  total_chunks integer not null,
  content bytea not null,
  updated_at timestamp without time zone not null default now(),
  primary key (upload_id, chunk_index)
);

create index if not exists ix_telemetria_id on public.telemetria (id);
create index if not exists ix_telemetria_idVehiculo on public.telemetria ("idVehiculo");
create index if not exists ix_telemetria_fechaHoraLecturaDato on public.telemetria ("fechaHoraLecturaDato");
create index if not exists ix_telemetria_fechaHoraEnvioDato on public.telemetria ("fechaHoraEnvioDato");
create index if not exists ix_telemetria_tramaRetransmitida on public.telemetria ("tramaRetransmitida");
create index if not exists ix_telemetria_latenciaMinutos on public.telemetria ("latenciaMinutos");
create index if not exists idx_vehiculo_fecha on public.telemetria ("idVehiculo", "fechaHoraLecturaDato");
create index if not exists idx_retrans_fecha on public.telemetria ("tramaRetransmitida", "fechaHoraLecturaDato");
create index if not exists ix_archivos_cargados_id on public.archivos_cargados (id);
create index if not exists idx_upload_chunks_updated_at on public.upload_chunks (updated_at);

alter table public.telemetria enable row level security;
alter table public.archivos_cargados enable row level security;
alter table public.upload_chunks enable row level security;
